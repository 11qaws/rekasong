function locale() {
  return document.documentElement.lang?.toLowerCase().startsWith('en') ? 'en' : 'ko';
}

export function getLyricsMessage(key, values = {}, selectedLocale = locale()) {
  const catalog = lyricsMessageCatalog[selectedLocale] || lyricsMessageCatalog.ko;
  let message = catalog[key] || lyricsMessageCatalog.en[key] || key;
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{{${name}}}`, String(value));
  }
  return message;
}
